import fs from 'node:fs/promises';
import path from 'node:path';

const rootDir = process.cwd();
const targetConfigs = [
  { dir: 'blink', browserName: 'Chromium' },
  { dir: 'moz', browserName: 'Firefox' }
];

const RUN_AT_MAP = {
  'document-start': 'document_start',
  'document-end': 'document_end',
  'document-idle': 'document_idle'
};

const USER_SCRIPT_SUFFIX = '.user.js';
const META_START = '// ==UserScript==';
const META_END = '// ==/UserScript==';
const RAW_PREFIX = 'https://raw.githubusercontent.com/digitalby/twitter-userscripts/main/';

function parseMetadata(source) {
  const start = source.indexOf(META_START);
  const end = source.indexOf(META_END);
  if (start === -1 || end === -1 || end < start) {
    throw new Error('Missing userscript metadata block.');
  }

  const metaLines = source.slice(start, end + META_END.length).split('\n');
  const metadata = {};

  for (const line of metaLines) {
    const match = line.match(/^\/\/\s*@([\w-]+)\s+(.+)$/);
    if (!match) continue;
    const [, key, rawValue] = match;
    const value = rawValue.trim();
    if (!metadata[key]) metadata[key] = [];
    metadata[key].push(value);
  }

  const codeWithoutMetadata =
    source.slice(0, start).trim() + '\n' + source.slice(end + META_END.length).trimStart();

  return { metadata, codeWithoutMetadata };
}

async function loadRequire(requireValue) {
  if (!requireValue.startsWith(RAW_PREFIX)) {
    throw new Error(`Unsupported @require source: ${requireValue}`);
  }

  const localFileName = requireValue.slice(RAW_PREFIX.length);
  const localPath = path.join(rootDir, localFileName);
  return fs.readFile(localPath, 'utf8');
}

async function loadScriptEntries() {
  const fileNames = await fs.readdir(rootDir);
  const userScriptFiles = fileNames
    .filter((file) => file.endsWith(USER_SCRIPT_SUFFIX))
    .sort();

  if (userScriptFiles.length === 0) {
    throw new Error(`No ${USER_SCRIPT_SUFFIX} files found in ${rootDir}`);
  }

  const scriptEntries = [];

  for (const fileName of userScriptFiles) {
    const fullPath = path.join(rootDir, fileName);
    const source = await fs.readFile(fullPath, 'utf8');
    const { metadata, codeWithoutMetadata } = parseMetadata(source);

    const requires = metadata.require ?? [];
    const requireChunks = [];
    for (const requireValue of requires) {
      requireChunks.push(await loadRequire(requireValue));
    }

    const outFileName = fileName.replace(USER_SCRIPT_SUFFIX, '.js');
    const runAt = RUN_AT_MAP[(metadata['run-at'] ?? ['document-idle'])[0]] ?? 'document_idle';

    scriptEntries.push({
      sourceFile: fileName,
      outFileName,
      name: (metadata.name ?? [fileName])[0],
      version: (metadata.version ?? ['0.0.0'])[0],
      matches: metadata.match ?? [],
      runAt,
      bundle: [...requireChunks, codeWithoutMetadata].join('\n\n') + '\n'
    });
  }

  return scriptEntries;
}

function makeManifest({ browserName, scriptEntries }) {
  const contentScripts = scriptEntries.map((entry) => ({
    matches: entry.matches,
    js: [`scripts/${entry.outFileName}`],
    run_at: entry.runAt
  }));

  const maxVersion = scriptEntries
    .map((entry) => entry.version)
    .sort((a, b) => a.localeCompare(b, undefined, { numeric: true }))
    .at(-1) ?? '1.0.0';

  const manifest = {
    manifest_version: 3,
    name: `Twitter Userscripts (${browserName})`,
    version: maxVersion,
    description: `Built from userscripts in this repository. Source files stay in place for userscript-manager installs.`,
    content_scripts: contentScripts
  };

  if (browserName === 'Firefox') {
    manifest.browser_specific_settings = {
      gecko: {
        id: 'twitter-userscripts@digitalby.github',
        strict_min_version: '109.0'
      }
    };
  }

  return manifest;
}

async function buildTarget({ dir, browserName }, scriptEntries) {
  const targetDir = path.join(rootDir, dir);
  const scriptsDir = path.join(targetDir, 'scripts');

  await fs.rm(targetDir, { recursive: true, force: true });
  await fs.mkdir(scriptsDir, { recursive: true });

  for (const entry of scriptEntries) {
    const outPath = path.join(scriptsDir, entry.outFileName);
    await fs.writeFile(outPath, entry.bundle, 'utf8');
  }

  const manifest = makeManifest({ browserName, scriptEntries });
  await fs.writeFile(
    path.join(targetDir, 'manifest.json'),
    `${JSON.stringify(manifest, null, 2)}\n`,
    'utf8'
  );

  const readme = [
    `# ${browserName} build output`,
    '',
    'Generated by `npm run build:extensions`.',
    'Do not edit files in this folder by hand.',
    ''
  ].join('\n');
  await fs.writeFile(path.join(targetDir, 'README.md'), readme, 'utf8');
}

async function main() {
  const scriptEntries = await loadScriptEntries();

  for (const target of targetConfigs) {
    await buildTarget(target, scriptEntries);
  }

  console.log(`Built ${scriptEntries.length} userscripts into blink/ and moz/.`);
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
